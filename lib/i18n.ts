export type StringKey = keyof typeof STRINGS;

/** Look up a string in the current language. `{name}`-style slots interpolate. Render-pure. */
export function t(key: StringKey, vars?: Record<string, string | number>): string {
  const lang = getLang();
  let s: string = STRINGS[key]?.[lang] ?? STRINGS[key]?.en ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** For class constants that need translation at render time (TOPICS, THEMES, PENS, MARKERS, FACES, TAGS, SORTS). */
export function tName(map: Record<string, { en: string; zh: string }>, key: string): string {
  const lang = getLang();
  return map[key]?.[lang] ?? map[key]?.en ?? key;
}

