/**
 * UI strings, both languages. One flat table, looked up by key; the current
 * language lives in settings and on <html lang>.
 *
 * Strings land here when they're shown to the user (labels, tips, empty
 * states, toasts). Internal names (actions, model ids, storage keys) and
 * anything rendered inside a text's own prose stay untranslated.
 */

export type Lang = "en" | "zh";

export function detectLang(): Lang {
  if (typeof window === "undefined") return "en";
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

// The source of truth for the current language. SSR and the first client render
// both return "en"; after hydration, LocalSync registers the store-backed source
// so t()/tName() see the saved lang.
let langSource: () => Lang = () => "en";
export function registerLangSource(fn: () => Lang): void {
  langSource = fn;
}
export function getLang(): Lang {
  return langSource();
}


